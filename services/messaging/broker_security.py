"""Generate broker credentials and ACLs for the secured Mosquitto broker (MQTT-07).

    python -m services.messaging.broker_security

writes, from shared/routes.json:

* infrastructure/mosquitto-secure/acl     topic rules from mosquitto_acl(): each bus may
                                          write only its own telemetry/heartbeat/alert topics
                                          and read only its own and its region's command topics;
                                          each edge reads its region and writes its own
                                          bus states/health/alerts; central reads states,
                                          health and alerts and writes commands
* infrastructure/mosquitto-secure/passwd  one account per service, Mosquitto PBKDF2-SHA512 hashes
* infrastructure/secure.env               the matching plaintext passwords for compose

passwd and secure.env hold secrets and are git-ignored. Re-running replaces all
passwords. compose.secure.yaml starts the broker with allow_anonymous false.
"""

import argparse
import base64
import hashlib
import json
import os
import secrets
from pathlib import Path

from services.edge.auth_edge_server import mosquitto_acl
from shared.schema.network import DEFAULT_NETWORK_PATH, load_network

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG_DIR = ROOT / "infrastructure" / "mosquitto-secure"
DEFAULT_ENV_FILE = ROOT / "infrastructure" / "secure.env"
PBKDF2_ITERATIONS = 101  # Mosquitto 2 default for $7$ hashes


def mosquitto_hash(
    password: str, *, salt: bytes | None = None, iterations: int = PBKDF2_ITERATIONS
) -> str:
    """Hash in mosquitto_passwd's $7$ format: PBKDF2-HMAC-SHA512, 12-byte salt."""
    salt = os.urandom(12) if salt is None else salt
    digest = hashlib.pbkdf2_hmac("sha512", password.encode("utf-8"), salt, iterations)
    return f"$7${iterations}${base64.b64encode(salt).decode()}${base64.b64encode(digest).decode()}"


def accounts(network) -> list[str]:
    """Every broker username, matching the users named in the ACL."""
    edges = [
        region[field]
        for region in network["regions"]
        for field in ("primary_edge", "backup_edge")
    ]
    return ["central", *edges, *(bus["bus_id"] for bus in network["buses"])]


def env_name(username: str) -> str:
    return username.upper().replace("-", "_") + "_MQTT_PASSWORD"


def generate(network, passwords: dict[str, str] | None = None) -> dict[str, str]:
    """Return {username: password}, generating any password not supplied."""
    passwords = dict(passwords or {})
    for username in accounts(network):
        passwords.setdefault(username, secrets.token_urlsafe(24))
    return passwords


def write(
    network, config_dir=DEFAULT_CONFIG_DIR, env_file=DEFAULT_ENV_FILE, passwords=None
) -> dict[str, str]:
    config_dir, env_file = Path(config_dir), Path(env_file)
    passwords = generate(network, passwords)
    config_dir.mkdir(parents=True, exist_ok=True)
    (config_dir / "acl").write_text(
        mosquitto_acl(network), encoding="utf-8", newline="\n"
    )
    (config_dir / "passwd").write_text(
        "".join(
            f"{user}:{mosquitto_hash(passwords[user])}\n" for user in accounts(network)
        ),
        encoding="utf-8",
        newline="\n",
    )
    buses = {bus["bus_id"]: passwords[bus["bus_id"]] for bus in network["buses"]}
    lines = [
        "# Generated by python -m services.messaging.broker_security. Secrets: do not commit."
    ]
    lines += [
        f"{env_name(user)}={passwords[user]}"
        for user in accounts(network)
        if user not in buses
    ]
    lines.append(
        f"MQTT_BUS_PASSWORDS_JSON='{json.dumps(buses, separators=(',', ':'))}'"
    )
    env_file.parent.mkdir(parents=True, exist_ok=True)
    env_file.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for path in (config_dir / "passwd", env_file):
        try:
            os.chmod(path, 0o600)
        except OSError:
            pass
    return passwords


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate Mosquitto passwd/acl and compose credentials."
    )
    parser.add_argument("--network", default=str(DEFAULT_NETWORK_PATH))
    parser.add_argument("--config-dir", default=str(DEFAULT_CONFIG_DIR))
    parser.add_argument("--env-file", default=str(DEFAULT_ENV_FILE))
    args = parser.parse_args(argv)
    network = load_network(args.network)
    passwords = write(network, args.config_dir, args.env_file)
    print(
        f"Wrote {len(passwords)} accounts to {args.config_dir} (acl, passwd) and {args.env_file}"
    )


if __name__ == "__main__":
    main()
